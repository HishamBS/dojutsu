#!/usr/bin/env bun
// Usage: create-inventory.ts <project_dir> <audit_dir>
// Walks the file tree, counts LOC, classifies layers, writes inventory.json.
// Deterministic: no LLM involved.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import type { Dirent } from "node:fs";
import { join } from "node:path";
import { dumpJson, isRecord, readHeadLines, readTextStrict } from "@quality/io.ts";
import type { Inventory, InventoryFile, InventoryLayer } from "@quality/types.ts";
import { isMetaFile } from "@rinnegan/meta-files.ts";

type LayerPatterns = readonly (readonly [string, readonly string[]])[];

const LAYER_PATTERNS: LayerPatterns = [
  ["api-routes", ["app/api/", "pages/api/", "src/app/api/"]],
  ["routes", ["routes/", "src/routes/"]],
  ["components", ["components/", "src/components/"]],
  ["modules", ["modules/", "src/modules/"]],
  ["hooks", ["hooks/", "src/hooks/"]],
  ["services", ["services/", "src/services/"]],
  ["types", ["types/", "src/types/", "@types/"]],
  ["config", ["config/", "configs/", "constants/", "src/config/"]],
  ["stores", ["store/", "stores/", "zustand/"]],
  ["utils", ["utils/", "lib/", "helpers/", "common/", "shared/"]],
  ["providers", ["providers/", "contexts/", "src/providers/"]],
  ["infrastructure", ["Dockerfile", "docker-compose", ".github/", ".gitlab-ci"]],
  ["tests", ["__tests__/", "test/", "spec/", ".test.", ".spec."]],
];

const JAVA_LAYER_PATTERNS: LayerPatterns = [
  ["controllers", ["controller.java", "/controller/", "/controllers/", "/rest/", "/web/"]],
  ["services", ["service.java", "/service/", "/services/"]],
  ["repositories", ["repository.java", "/repository/", "/repositories/", "/dao/"]],
  ["dto", ["/dto/", "dto.java", "request.java", "response.java", "requestdto.java", "responsedto.java"]],
  ["entities", ["/entity/", "/entities/", "/model/", "/domain/"]],
  ["config", ["config.java", "configuration.java", "/config/", "/configuration/"]],
  ["mappers", ["mapper.java", "/mapper/", "/mappers/", "/converter/"]],
  ["utils", ["/util/", "/utils/", "/helper/", "/common/"]],
  ["tests", ["/test/", "test.java", "tests.java", "/it/", "integrationtest"]],
];

const PYTHON_LAYER_PATTERNS: LayerPatterns = [
  ["routes", ["/routes/", "/endpoints/", "/views/", "/routers/"]],
  ["services", ["/services/", "/service/"]],
  ["models", ["/models/", "/schemas/", "/entities/"]],
  ["utils", ["/utils/", "/helpers/", "/common/", "/shared/"]],
  ["config", ["/config/", "/configs/", "/settings/", "settings.py", "config.py"]],
  ["tests", ["/tests/", "/test/", "test_", "_test.py", "conftest.py"]],
  ["middleware", ["/middleware/", "/middlewares/"]],
  ["agents", ["/agents/", "/tools/", "/prompts/"]],
];

const GO_LAYER_PATTERNS: LayerPatterns = [
  ["cmd", ["/cmd/"]],
  ["internal", ["/internal/"]],
  ["pkg", ["/pkg/"]],
  ["handlers", ["/handler/", "/handlers/"]],
  ["services", ["/service/", "/services/"]],
  ["models", ["/model/", "/models/"]],
  ["middleware", ["/middleware/"]],
  ["utils", ["/util/", "/utils/", "/pkg/util"]],
  ["tests", ["_test.go"]],
];

const STACK_LAYER_PATTERNS: Readonly<Record<string, LayerPatterns>> = {
  java: JAVA_LAYER_PATTERNS,
  python: PYTHON_LAYER_PATTERNS,
  go: GO_LAYER_PATTERNS,
};

const MAX_FILE_LOC = 10_000;
const NOMINAL_LOC_THRESHOLD = 10;
const GENERATED_HEADER_LINES = 5;
const UNKNOWN = "unknown";
const MISC_LAYER = "misc";

const SKIP_DIRS: ReadonlySet<string> = new Set([
  "node_modules", ".next", "__pycache__", ".git", "dist", "build", ".venv", "venv", ".turbo", ".cache", "coverage", ".nyc_output",
]);

const EXTENSIONS: Readonly<Record<string, readonly string[]>> = {
  typescript: [".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"],
  python: [".py"],
  java: [".java", ".kt", ".kts"],
  go: [".go"],
  rust: [".rs"],
};
const DEFAULT_EXTENSIONS: readonly string[] = [".ts", ".tsx", ".py", ".java"];

const TEST_PATH_MARKERS: readonly string[] = ["__tests__/", ".test.", ".spec.", "/test/", "/tests/"];
const GENERATED_PATH_MARKERS: readonly string[] = ["generated/", "auto-generated"];
const GENERATED_HEADER_MARKERS: readonly string[] = ["generated by", "auto-generated", "autogenerated", "do not edit", "@generated"];

const NODE_FRAMEWORKS: readonly (readonly [string, string])[] = [
  ["next", "nextjs"],
  ["react", "react"],
  ["vue", "vue"],
  ["express", "express"],
];
const PYTHON_FRAMEWORKS: readonly (readonly [string, string])[] = [
  ["fastapi", "fastapi"],
  ["django", "django"],
  ["flask", "flask"],
];

const isFile = (path: string): boolean => existsSync(path) && statSync(path).isFile();

// Newline-terminated lines plus an unterminated last line, with \r\n and \r as breaks.
function countLines(bytes: Buffer): number {
  const LF = 0x0a;
  const CR = 0x0d;
  let count = 0;
  for (let i = 0; i < bytes.length; i += 1) {
    const byte = bytes[i];
    if (byte === LF || (byte === CR && bytes[i + 1] !== LF)) count += 1;
  }
  const last = bytes[bytes.length - 1];
  return last === undefined || last === LF || last === CR ? count : count + 1;
}

function readLoc(path: string): number {
  try {
    return countLines(readFileSync(path));
  } catch {
    return 0;
  }
}

function hasGeneratedMarker(path: string): boolean {
  try {
    const header = readHeadLines(path, GENERATED_HEADER_LINES, false).toLowerCase();
    return GENERATED_HEADER_MARKERS.some((marker) => header.includes(marker));
  } catch {
    return false;
  }
}

// Newline-separated path prefixes from <project>/.rinnegan/authority-paths.txt; no defaults.
function readAuthorityPaths(projectDir: string): string[] {
  const path = join(projectDir, ".rinnegan", "authority-paths.txt");
  if (!isFile(path)) return [];
  return readTextStrict(path)
    .split(/\r\n|\r|\n/)
    .filter((line) => line.trim() !== "" && !line.startsWith("#"))
    .map((line) => line.trim());
}

function frameworkFrom(manifest: unknown): string {
  if (!isRecord(manifest)) return UNKNOWN;
  const deps: Record<string, unknown> = {};
  for (const key of ["dependencies", "devDependencies"]) {
    const section = key in manifest ? manifest[key] : {};
    if (!isRecord(section)) return UNKNOWN;
    Object.assign(deps, section);
  }
  return NODE_FRAMEWORKS.find(([dep]) => Object.hasOwn(deps, dep))?.[1] ?? UNKNOWN;
}

function detectStack(projectDir: string): { stack: string; framework: string } {
  const manifestPath = join(projectDir, "package.json");
  const pyprojectPath = join(projectDir, "pyproject.toml");
  if (existsSync(manifestPath)) {
    try {
      return { stack: "typescript", framework: frameworkFrom(JSON.parse(readTextStrict(manifestPath))) };
    } catch {
      return { stack: "typescript", framework: UNKNOWN };
    }
  }
  if (existsSync(pyprojectPath) || existsSync(join(projectDir, "requirements.txt"))) {
    let framework = UNKNOWN;
    if (existsSync(pyprojectPath)) {
      try {
        const content = readTextStrict(pyprojectPath).toLowerCase();
        framework = PYTHON_FRAMEWORKS.find(([name]) => content.includes(name))?.[1] ?? UNKNOWN;
      } catch {
        framework = UNKNOWN;
      }
    }
    return { stack: "python", framework };
  }
  if (existsSync(join(projectDir, "pom.xml")) || existsSync(join(projectDir, "build.gradle"))) {
    return { stack: "java", framework: UNKNOWN };
  }
  return { stack: UNKNOWN, framework: UNKNOWN };
}

function classifyLayer(relLower: string, stack: string): string {
  for (const patterns of [STACK_LAYER_PATTERNS[stack] ?? [], LAYER_PATTERNS]) {
    for (const [layer, markers] of patterns) {
      if (markers.some((marker) => relLower.includes(marker))) return layer;
    }
  }
  return MISC_LAYER;
}

// A symlinked directory is neither listed as a file nor descended into.
function isDirectory(entry: Dirent, absPath: string): boolean {
  if (entry.isDirectory()) return true;
  if (!entry.isSymbolicLink()) return false;
  try {
    return statSync(absPath).isDirectory();
  } catch {
    return false;
  }
}

// Top-down like os.walk: a directory's files, then its subdirectories, in name order.
// Unreadable directories are skipped silently, as os.walk does.
function walkFiles(projectDir: string, relDir: string, out: string[]): void {
  let entries: Dirent[];
  try {
    entries = readdirSync(join(projectDir, relDir), { withFileTypes: true });
  } catch {
    return;
  }
  entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const subdirs: string[] = [];
  for (const entry of entries) {
    const rel = relDir === "" ? entry.name : `${relDir}/${entry.name}`;
    if (isDirectory(entry, join(projectDir, rel))) {
      if (!SKIP_DIRS.has(entry.name) && !entry.isSymbolicLink()) subdirs.push(rel);
    } else {
      out.push(rel);
    }
  }
  for (const sub of subdirs) walkFiles(projectDir, sub, out);
}

export function buildInventory(projectDir: string, auditDir?: string): Inventory {
  const { stack, framework } = detectStack(projectDir);
  const authorityPaths = readAuthorityPaths(projectDir);
  const extensions = EXTENSIONS[stack] ?? DEFAULT_EXTENSIONS;

  const relPaths: string[] = [];
  walkFiles(projectDir, "", relPaths);

  const files: InventoryFile[] = [];
  const layers: Record<string, InventoryLayer> = {};
  let totalLoc = 0;
  for (const relPath of relPaths) {
    if (!extensions.some((ext) => relPath.endsWith(ext))) continue;
    const absPath = join(projectDir, relPath);
    const loc = readLoc(absPath);
    const normalized = relPath.replaceAll("\\", "/");
    const relLower = normalized.toLowerCase();
    const layer = classifyLayer(relLower, stack);

    let tag = "SOURCE";
    let skipReason: string | undefined;
    if (TEST_PATH_MARKERS.some((marker) => relLower.includes(marker))) {
      tag = "TEST";
    } else if (GENERATED_PATH_MARKERS.some((marker) => relLower.includes(marker)) || hasGeneratedMarker(absPath)) {
      tag = "GENERATED";
      skipReason = "Generated source file";
    }
    if (loc > MAX_FILE_LOC) {
      tag = "OVERSIZED";
      skipReason = `Exceeds ${MAX_FILE_LOC} LOC limit (${loc} lines)`;
    }

    const nominal = loc < NOMINAL_LOC_THRESHOLD && !authorityPaths.some((prefix) => normalized.startsWith(prefix));
    const entry: InventoryFile = { path: relPath, loc, layer, tag, nominal, is_meta_file: isMetaFile(normalized, projectDir) };
    if (skipReason !== undefined) entry.skip_reason = skipReason;
    files.push(entry);
    totalLoc += loc;
    const bucket = (layers[layer] ??= { files: [], loc: 0 });
    bucket.files.push(relPath);
    bucket.loc += loc;
  }

  const inventory: Inventory = {
    root: projectDir.slice(projectDir.lastIndexOf("/") + 1),
    stack,
    framework,
    total_files: files.length,
    total_loc: totalLoc,
    layers,
    files,
  };

  if (auditDir !== undefined) {
    for (const dir of ["data/scanner-output", "data/tasks", "layers", "phases"]) mkdirSync(join(auditDir, dir), { recursive: true });
    writeFileSync(join(auditDir, "data", "inventory.json"), dumpJson(inventory));
    writeFileSync(join(auditDir, "data", "scanner-output", "scope-map.json"), "{}");
  }
  return inventory;
}

if (import.meta.main) {
  const [projectDir, auditDir] = process.argv.slice(2);
  if (projectDir === undefined || auditDir === undefined) {
    console.error("Usage: create-inventory.ts <project_dir> <audit_dir>");
    process.exit(1);
  }
  const inventory = buildInventory(projectDir, auditDir);
  console.log(`Stack: ${inventory.stack}/${inventory.framework}`);
  console.log(`Files: ${inventory.files.length}, LOC: ${inventory.total_loc}, Layers: ${Object.keys(inventory.layers).length}`);
  for (const [name, data] of Object.entries(inventory.layers).sort(([, a], [, b]) => b.loc - a.loc)) {
    console.log(`  ${name}: ${data.files.length} files, ${data.loc} LOC`);
  }
  console.log(`Output: ${auditDir}/data/inventory.json`);
  console.log(`Directories created: ${auditDir}/{data,layers,phases}`);
}
